function readOtpSecret(): string {
  const secret = process.env.OTP_SECRET ?? '';
  if (process.env.NODE_ENV === 'production' && (secret.startsWith('replace_with') || secret.length < 32)) {
    throw new Error('OTP_SECRET must be a real random secret (≥ 32 chars) in production');
  }
  return secret;
}

/**
 * TOTP_ENCRYPTION_KEY: 32 random bytes, base64 (e.g. `node -e "console.log(require('crypto').randomBytes(32).toString('base64'))"`).
 * Outside production, falls back to a key derived from OTP_SECRET so local setups keep working.
 */
function readTotpKey(otpSecret: string): Buffer {
  const raw = process.env.TOTP_ENCRYPTION_KEY;
  if (raw) {
    const key = Buffer.from(raw, 'base64');
    if (key.length !== 32) throw new Error('TOTP_ENCRYPTION_KEY must be 32 bytes, base64-encoded');
    return key;
  }
  if (process.env.NODE_ENV === 'production') throw new Error('TOTP_ENCRYPTION_KEY is required in production');
  return createHash('sha256').update(`totp-dev-key:${otpSecret}`).digest();
}

function readDevEcho(): boolean {
  const on = process.env.OTP_DEV_ECHO === 'true';
  if (on && process.env.NODE_ENV === 'production') {
    throw new Error('OTP_DEV_ECHO must not be enabled in production');
  }
  return on;
}

let singleton: AccountsOtpService | null = null;

export function getAccountsOtpService(): AccountsOtpService {
  if (!singleton) {
    const otpSecret = readOtpSecret();
    const kv = getKeyValueStore();
    // OTP_CHANNEL (OD-09). Production fails closed here until the real channel exists.
    const delivery = createOtpDelivery(process.env, kv);
    singleton = new AccountsOtpService({
      kv,
      repo: new PgAccountsRepo(),
      sender: delivery.sender,
      ...(delivery.mockInbox ? { mockInbox: delivery.mockInbox } : {}),
      getNumber: getConfigNumber,
      otpSecret,
      devEcho: readDevEcho(),
      totpKey: readTotpKey(otpSecret),
    });
  }
  return singleton;
}

/** For other modules: revoke all sessions when an account is banned/suspended (SEC-1.7). */
export function revokeAllSessionsForUser(userId: string): Promise<void> {
  return getAccountsOtpService().sessions.revokeAllForUser(userId);
}
